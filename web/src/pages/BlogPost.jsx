export default function BlogPost() {
  const { slug } = useParams();
  const article = ARTICLES[slug];

  if (!article) return (
    <div className="max-w-3xl mx-auto px-4 py-12 text-center text-gray-500">
      Article not found. <Link to="/blog" className="text-purple-700 hover:underline">Back to Blog</Link>
    </div>
  );

  return (
    <div className="max-w-3xl mx-auto px-4 py-8">
      <Link to="/blog" className="text-purple-700 text-sm mb-4 inline-block hover:underline">&larr; Back to Blog</Link>
      <article className="bg-white rounded-2xl border border-gray-100 shadow-sm p-6 md:p-8">
        <div className="flex flex-wrap gap-2 mb-3">
          {article.tags.map(tag => (
            <span key={tag} className="text-xs bg-purple-50 text-purple-700 px-2 py-0.5 rounded-full">{tag}</span>
          ))}
        </div>
        <h1 className="text-2xl md:text-3xl font-bold mb-2">{article.title}</h1>
        <p className="text-sm text-gray-500 mb-6">{article.date}</p>
        <div className="prose prose-sm max-w-none text-gray-700 leading-relaxed space-y-4"
          dangerouslySetInnerHTML={{ __html: article.body.split('\n\n').map(p => {
            if (p.startsWith('## ')) return `<h2 class="text-lg font-semibold text-gray-900 mt-6 mb-2">${p.slice(3)}</h2>`;
            if (p.startsWith('| ')) {
              const lines = p.split('\n');
              const thead = `<thead><tr>${lines[0].split('|').filter(c => c.trim()).map(c => `<th class="border px-3 py-1 text-left text-sm">${c.trim()}</th>`).join('')}</tr></thead>`;
              const tbody = `<tbody>${lines.slice(2).map(line => `<tr>${line.split('|').filter(c => c.trim()).map(c => `<td class="border px-3 py-1 text-sm">${c.trim()}</td>`).join('')}</tr>`).join('')}</tbody>`;
              return `<table class="w-full my-3 border-collapse text-sm">${thead}${tbody}</table>`;
            }
            if (/^\d+\./.test(p)) {
              const items = p.split('\n').map(line => {
                const m = line.match(/^\d+\.\s+\*\*(.+?)\*\*\s*—\s*(.+)/);
                return m ? `<li><strong>${m[1]}</strong> — ${m[2]}</li>` : `<li>${line.replace(/^\d+\.\s+/, '')}</li>`;
              });
              return `<ol class="list-decimal ml-5 space-y-1">${items.join('')}</ol>`;
            }
            if (p.startsWith('- ')) {
              const items = p.split('\n').map(line => `<li>${line.slice(2)}</li>`);
              return `<ul class="list-disc ml-5 space-y-1">${items.join('')}</ul>`;
            }
            return `<p>${p}</p>`;
          }).join('') }} />
        <div className="mt-8 pt-6 border-t border-gray-100">
          <Link to="/catalogue" className="inline-flex items-center gap-2 bg-purple-600 text-white px-6 py-3 rounded-xl font-medium hover:bg-purple-700 transition-colors">
            🛍️ Browse Catalogue
          </Link>
        </div>
      </article>
    </div>
  );
}
